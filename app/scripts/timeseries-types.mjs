// Generate frontend types from the checked-in subset of backend OpenAPI schemas.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const HERE = dirname(fileURLToPath(import.meta.url));
const CONTRACT = resolve(HERE, "../contracts/timeseries.schema.json");
const TYPES = resolve(HERE, "../types/timeseries.ts");
const GENERATED_FROM = "openskope/skope-api OpenAPI components";
const MODELS = [
  "TimeseriesRequest",
  "TimeseriesAnalyzeRequest",
  "TimeseriesResponse",
  "JobStatusResponse",
  "ExtractionAcceptedResponse",
  "JobErrorResponse",
];

function prepare(node, definition = false) {
  if (Array.isArray(node)) return node.map((item) => prepare(item));
  if (!node || typeof node !== "object") return node;
  return Object.fromEntries(
    Object.entries(node).flatMap(([key, value]) => {
      if (key === "title" && !definition) return [];
      if (key === "prefixItems") return [["items", prepare(value)]];
      if (key === "$defs" || key === "properties") {
        return [
          [
            key,
            Object.fromEntries(
              Object.entries(value).map(([name, schema]) => [
                name,
                prepare(schema, key === "$defs"),
              ]),
            ),
          ],
        ];
      }
      return [[key, prepare(value)]];
    }),
  );
}

export function contractFromOpenapi(openapi) {
  const definitions = {};
  function include(name) {
    if (definitions[name]) return;
    const schema = openapi.components.schemas[name];
    if (!schema) throw new Error(`Missing backend schema: ${name}`);
    definitions[name] = schema;
    const refs = JSON.stringify(schema).matchAll(
      /#\/components\/schemas\/([^"\\]+)/g,
    );
    for (const [, referenced] of refs) include(referenced);
  }
  MODELS.forEach(include);
  return JSON.parse(
    JSON.stringify({
      $schema: "https://json-schema.org/draft/2020-12/schema",
      title: "TimeseriesContracts",
      "x-skope-generated-from": GENERATED_FROM,
      type: "object",
      additionalProperties: false,
      properties: Object.fromEntries(
        MODELS.map((name) => [name, { $ref: `#/$defs/${name}` }]),
      ),
      $defs: definitions,
    }).replaceAll("#/components/schemas/", "#/$defs/"),
  );
}

export async function generateTimeseriesTypes() {
  const schema = JSON.parse(await readFile(CONTRACT, "utf8"));
  const prepared = { ...prepare(schema), title: "TimeseriesContracts" };
  // OpenAPI discriminators require their tag even when a standalone model
  // supplies a default. Preserve that requirement in TypeScript unions.
  function tagUnions(node) {
    if (!node || typeof node !== "object") return;
    if (node.discriminator?.mapping) {
      for (const reference of Object.values(node.discriminator.mapping)) {
        const definition = prepared.$defs[reference.replace("#/$defs/", "")];
        if (definition)
          definition.required = [
            ...new Set([
              ...(definition.required || []),
              node.discriminator.propertyName,
            ]),
          ];
      }
    }
    Object.values(node).forEach(tagUnions);
  }
  tagUnions(schema);
  return compile(prepared, "TimeseriesContracts", {
    additionalProperties: false,
    bannerComment: `/**\n * Generated by scripts/timeseries-types.mjs from contracts/timeseries.schema.json.\n * Backend schema origin: ${schema["x-skope-generated-from"]}. Do not edit by hand.\n */\n/* eslint-disable @typescript-eslint/no-empty-object-type */`,
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [openapiPath, ...extra] = process.argv.slice(2);
  if (extra.length)
    throw new Error("Usage: npm run types:timeseries -- [openapi.json]");
  if (openapiPath) {
    const schema = contractFromOpenapi(
      JSON.parse(await readFile(openapiPath, "utf8")),
    );
    await writeFile(CONTRACT, JSON.stringify(schema, null, 2) + "\n");
  }
  await writeFile(TYPES, await generateTimeseriesTypes());
}
